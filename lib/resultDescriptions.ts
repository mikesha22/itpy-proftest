function rangeIndex(value: number) {
  if (value >= 80) return 3;
  if (value >= 60) return 2;
  if (value >= 40) return 1;
  return 0;
}

export function scoreDescription(key: MainScoreKey, value: number) {
  return descriptions[key][rangeIndex(value)];
}

export function scoreGrowthAdvice(key: MainScoreKey) {
  return growthAdvice[key];
}

export function codeDescription(value: number) {
  if (value >= 80) {
    return "Ты уверенно читаешь простой Python-код, отслеживаешь переменные и понимаешь условия.";
  }
  if (value >= 60) {
    return "Базовая логика Python в целом понятна. Следующий шаг — самостоятельно написать несколько коротких программ.";
  }
  if (value >= 40) {
    return "Отдельные конструкции уже понятны, но чтение кода пока требует пошаговой записи значений.";
  }
  return "Python пока остаётся новым форматом. Начать лучше с переменных, условий и коротких программ без сложного синтаксиса.";
}

export function rankedScores(scores: Scores) {
  return resultScoreItems
    .map((item) => ({ ...item, value: Number(scores[item.key]) }))
    .sort((a, b) => b.value - a.value);
}
